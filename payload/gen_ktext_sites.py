#!/usr/bin/env python3
"""Generate the KASLR return-site table from an exact Honor kernel Image.

Every table entry is the image offset immediately after a direct
`bl schedule` or `bl io_schedule`. At runtime, a traced return address minus
one of these offsets produces a candidate kernel-text base.
"""
import argparse
import hashlib
import struct
from pathlib import Path

FILE_OFFSET = 0x7C0
LINK_BASE = 0xFFFFFFC080000000
TARGETS = {
    LINK_BASE + 0x1146324: "schedule",
    LINK_BASE + 0x11466A4: "io_schedule",
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", type=Path, required=True,
                        help="uncompressed kernel Image matching Image_175")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parent / "src/ktext_sites.h")
    args = parser.parse_args()

    data = args.image.read_bytes()
    sites = []
    counts = {name: 0 for name in TARGETS.values()}
    for off in range(0, len(data) - FILE_OFFSET - 4, 4):
        insn = struct.unpack_from("<I", data, FILE_OFFSET + off)[0]
        if insn >> 24 != 0x94:
            continue
        imm = insn & 0x3FFFFFF
        if imm >> 25:
            imm -= 0x4000000
        target = LINK_BASE + off + imm * 4
        if target in TARGETS:
            sites.append(off + 4)
            counts[TARGETS[target]] += 1
    if counts != {"schedule": 387, "io_schedule": 13}:
        raise SystemExit(f"unexpected call-site counts {counts}; "
                         "this generator currently validates Image_175 only")

    lines = [
        "/* Generated by gen_ktext_sites.py; do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"/* schedule={counts['schedule']}, io_schedule={counts['io_schedule']} */",
        "static const uint32_t KTEXT_CALL_SITES[] = {",
    ]
    for i in range(0, len(sites), 6):
        lines.append("  " + ", ".join(f"0x{x:08x}u" for x in sites[i:i + 6]) + ",")
    lines += [
        "};",
        "#define KTEXT_CALL_SITE_COUNT (sizeof(KTEXT_CALL_SITES) / sizeof(KTEXT_CALL_SITES[0]))",
        "",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines))
    print(f"image_sha256={hashlib.sha256(data).hexdigest()}")
    print(f"wrote {args.output}: {len(sites)} sites {counts}")


if __name__ == "__main__":
    main()
